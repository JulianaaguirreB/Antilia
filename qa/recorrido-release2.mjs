  await snap('01-inicio');
  await page.locator('nav').getByText('Espacios',{exact:true}).click();
  await page.getByRole('button',{name:'Agregar espacio',exact:true}).click();
  await page.getByLabel('Nombre del espacio',{exact:true}).fill('Escritorio de pruebas');
